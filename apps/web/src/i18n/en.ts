/** Why a follow-up did not come back, said from the word the server keeps (apps/server/src/followups.ts, `Why`). */
/** A sum kept in millionths of a dollar, as it is said in a notice. */
const usd = (micros: string | null | undefined) => `$${(Number(micros ?? 0) / 1e6).toFixed(2)}`;
/** Whose budget a notice is about. */
const budgetOf = (d: Record<string, string | null>) =>
  d.scope === "company"
    ? "The company's budget"
    : d.scope === "department"
      ? `The budget of ${d.name ?? "a department"}`
      : "Your limit";
